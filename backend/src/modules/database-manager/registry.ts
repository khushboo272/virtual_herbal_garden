// ── Validation Schemas ──────────────────────────────────────────

export const CategoryZodSchema = z.object({
  name: z.string().min(1, 'Category name is required').max(100),
  slug: z.string().min(1, 'Slug is required').regex(/^[a-z0-9-]+$/, 'Slug must be lowercase alphanumeric with hyphens'),
  description: z.string().nullable().optional(),
  sortOrder: z.number().int().default(0),
}).passthrough();

export const PlantZodSchema = z.object({
  commonName: z.string().min(1, 'Common name is required'),
  scientificName: z.string().min(1, 'Scientific name is required'),
  slug: z.string().min(1, 'Slug is required').regex(/^[a-z0-9-]+$/, 'Slug must be lowercase alphanumeric with hyphens'),
  family: z.string().min(1, 'Botanical family is required'),
  description: z.string().min(5, 'Description is required'),
  shortDescription: z.string().optional(),
  medicinalUses: z.array(z.string()).default([]),
  partsUsed: z.array(z.string()).default([]),
  toxicityLevel: z.enum(['NONE', 'LOW', 'MODERATE', 'HIGH']).default('NONE'),
  ayurvedicNames: z.array(z.string()).default([]),
  regionNative: z.array(z.string()).default([]),
  growingConditions: z.record(z.string(), z.any()).optional(),
  images: z.array(z.record(z.string(), z.any())).default([]),
  categories: z.array(z.any()).default([]),
  tags: z.array(z.string()).default([]),
  isFeatured: z.boolean().default(false),
  isPublished: z.boolean().default(true),
  placement3d: z.record(z.string(), z.any()).optional(),
  visual: z.record(z.string(), z.any()).optional(),
  aliases: z.array(z.string()).optional(),
  precautions: z.array(z.string()).optional(),
  references: z.array(z.any()).optional(),
}).passthrough();

export const RemedyZodSchema = z.object({
  title: z.string().min(1, 'Remedy title is required'),
  slug: z.string().min(1, 'Slug is required').regex(/^[a-z0-9-]+$/),
  description: z.string().min(5, 'Description is required'),
  plants: z.array(z.any()).default([]),
  dosage: z.string().optional(),
  ingredients: z.array(z.record(z.string(), z.any())).default([]),
  preparationSteps: z.array(z.record(z.string(), z.any())).default([]),
  contraindications: z.array(z.string()).default([]),
  difficultyLevel: z.enum(['EASY', 'MEDIUM', 'ADVANCED']).default('EASY'),
  preparationTime: z.number().default(10),
  tags: z.array(z.string()).default([]),
  isPublished: z.boolean().default(true),
}).passthrough();

export const TourZodSchema = z.object({
  title: z.string().min(1, 'Tour title is required'),
  slug: z.string().min(1, 'Slug is required').regex(/^[a-z0-9-]+$/),
  description: z.string().min(5, 'Description is required'),
  difficulty: z.enum(['EASY', 'MEDIUM', 'HARD', 'ADVANCED']).default('EASY'),
  estimatedDuration: z.number().default(15),
  coverImageUrl: z.string().nullable().optional(),
  stops: z.array(z.record(z.string(), z.any())).default([]),
  checkpoints: z.array(z.record(z.string(), z.any())).optional(),
  isPublished: z.boolean().default(true),
}).passthrough();

