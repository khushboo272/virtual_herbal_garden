export function getRegistryItem(key: string): CollectionRegistryItem | null {
  return COLLECTION_REGISTRY[key as CollectionKey] || null;
}

export function getAllRegistryItems(): CollectionRegistryItem[] {
  return Object.values(COLLECTION_REGISTRY);
}

export function isContentCollection(key: string): boolean {
  return ['categories', 'plants', 'remedies', 'tours'].includes(key);
}
